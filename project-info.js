export function renderProjectInfo(kind,lang) {
  const locale=copy[lang] ?? copy.kk;
  const w=locale[kind];
  if(!w || !['organizations','about'].includes(kind)) return null;
  const org=kind==='organizations';
  return `<main class="project-info project-info-${kind}">
    <section class="project-info-hero">
      <div class="wrap project-info-wrap project-info-hero-shell">
      <nav class="project-info-crumb" aria-label="${lang==='ru'?'Разделы':'Бөлімдер'}"><a href="/" data-link>${locale.home}</a><span aria-hidden="true">/</span><span aria-current="page">${w.title}</span></nav>
        <div class="project-info-intro">
          <h1>${w.title}</h1>
          <p class="project-info-lead">${w.lead}</p>
          <p>${w.intro}</p>
          <a class="button primary project-info-anchor" href="#project-paths">${w.browse}</a>
        </div>
      </div>
    </section>
    <div class="wrap project-info-wrap">
      <section id="project-paths" class="project-info-content" aria-labelledby="project-paths-title">
        <h2 id="project-paths-title">${w.sections}</h2>
        <div class="project-info-paths">
          ${w.rows.map(([title,description,label,url])=>`<article class="project-info-path">
            <div><h3>${title}</h3><p>${description}</p></div>
            <a href="${url}" data-link>${label}</a>
          </article>`).join('')}
        </div>
      </section>
      ${org?`<details class="project-info-checklist"><summary>${w.details}</summary><ol>${w.checklist.map(line=>`<li>${line}</li>`).join('')}</ol></details>`:
        `<section id="how" class="project-info-how" aria-labelledby="project-how-title"><h2 id="project-how-title">${w.how}</h2><ol>${w.steps.map(([title,description])=>`<li><strong>${title}</strong><p>${description}</p></li>`).join('')}</ol></section>`}
      <p class="project-info-notice" role="note">${w.note}</p>
    </div>
  </main>`;
}
